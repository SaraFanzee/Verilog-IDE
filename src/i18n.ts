export type Locale = 'zh-CN' | 'en';
export type MessageKey = keyof typeof messages;
export const localeStorageKey = 'verilog-ide-locale';
export const isEnglish = (locale: unknown): locale is 'en' => locale === 'en';

type Values = Record<string, string | number | null>;
export interface Message { key: MessageKey; values?: Values }

export function message(key: MessageKey, values?: Values): Message { return { key, values }; }

function preferredLocale(): Locale {
  try { return isEnglish(localStorage.getItem(localeStorageKey)) ? 'en' : 'zh-CN'; }
  catch { return 'zh-CN'; }
}

export const startupLocale = preferredLocale();
let locale = startupLocale;
export function getLocale() { return locale; }
export function setLocale(value: Locale) { locale = value; }

export function translate(content: Message | string, language = locale): string {
  if (typeof content === 'string') return content;
  return messages[content.key][isEnglish(language) ? 1 : 0]
    .replace(/\{(\w+)\}/g, (placeholder, name: string) => {
      const value = content.values?.[name];
      return value === undefined ? placeholder : String(value);
    });
}

export function t(key: MessageKey, values?: Values): string { return translate(message(key, values)); }

export class LocalizedError extends Error {
  constructor(readonly detail: Message) { super(translate(detail)); }
}

export function errorMessage(error: unknown): Message | string {
  return error instanceof LocalizedError ? error.detail : error instanceof Error ? error.message : String(error);
}
